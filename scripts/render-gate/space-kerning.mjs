#!/usr/bin/env node
// Writes the native screens' space-kerning table (SpaceKerning.kt) from the site's own web fonts, as Blink shapes them.
// Blink shapes a whole text run, so a font's kern pairs against the space glyph apply (Archivo: "k " / "r " / "Y" either
// side; "drink (weekly)" came out 0.49 px wider natively). Android's Minikin shapes word by word with the space apart and
// never applies them; CssText (ScreenKit) adds each pair back as letter spacing on the space (RENDER-GATE-SPACE-KERNING-2026-10-24,
// healer:4b3d7c53). Re-run when a site font or a native font weight changes:
//   space-kerning.mjs --site URL --path P --har F --out SpaceKerning.kt --token-key K --fonts "res|css family|w,w;..."
// res = the app's font resource name (res/font/<res>.ttf); css family = a font-family value on the page (var(--x) is fine).
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1]])
  return acc
}, []))
for (const k of ['site', 'path', 'har', 'out', 'fonts']) if (!args[k]) { console.error(`space-kerning.mjs: --${k} is required`); process.exit(2) }
const fonts = args.fonts.split(';').filter(Boolean).map(row => {
  const [res, family, weights] = row.split('|')
  return { res, family, weights: weights.split(',').map(Number) }
})

// Advance of "c " and " c" against "c" + " " at 1000 px (Blink positions are 1/64 px, so 1.6e-5 em resolution).
const probe = `(() => {
  const chars = [...new Set([...${JSON.stringify(String.fromCharCode(...Array.from({ length: 94 }, (_, i) => 33 + i)) + '£€’‘“”–—…')}])]
  const fonts = ${JSON.stringify(fonts)}
  const el = document.createElement('span')
  el.style.cssText = 'font-size:1000px;white-space:pre;position:absolute;top:0;left:0;letter-spacing:0;font-kerning:auto'
  document.body.appendChild(el)
  const w = t => { el.textContent = t; return el.getBoundingClientRect().width }
  const out = []
  for (const f of fonts) for (const weight of f.weights) {
    el.style.fontFamily = f.family; el.style.fontWeight = String(weight)
    const sp = w(' '), after = {}, before = {}
    for (const c of chars) {
      const a = w(c)
      const x = (w(c + ' ') - a - sp) / 1000, y = (w(' ' + c) - a - sp) / 1000
      if (Math.abs(x) >= 0.0005) after[c] = +x.toFixed(5)
      if (Math.abs(y) >= 0.0005) before[c] = +y.toFixed(5)
    }
    out.push({ res: f.res, weight, after, before })
  }
  el.remove()
  return out
})()`
const here = dirname(fileURLToPath(import.meta.url))
const raw = execFileSync('node', [join(here, 'reference.mjs'), '--site', args.site, '--path', args.path, '--har', args.har,
  '--out', `${args.out}.page.png`, '--token-key', args['token-key'] || 'randalls_member_token', '--eval', probe], { encoding: 'utf8' })
const rows = JSON.parse(raw.split('\n').find(l => l.startsWith('[')))
execFileSync('rm', ['-f', `${args.out}.page.png`])

const kc = c => `'${c === '\\' ? '\\\\' : c === "'" ? "\\'" : c}'`
const map = m => Object.keys(m).length ? `mapOf(${Object.entries(m).map(([c, v]) => `${kc(c)} to ${v}f`).join(', ')})` : 'emptyMap()'
const byRes = {}
for (const r of rows) (byRes[r.res] ||= []).push(r)
const body = Object.entries(byRes).map(([res, ws]) => `        "${res}" to mapOf(\n${ws.map(r =>
  `            ${r.weight} to SpaceKern(after = ${map(r.after)}, before = ${map(r.before)}),`).join('\n')}\n        ),`).join('\n')
writeFileSync(args.out, `// GENERATED by scripts/render-gate/space-kerning.mjs from ${args.site}${args.path} (the site's web fonts, shaped by Blink).
// Do not edit; re-run the script when a site font or a native font weight changes.
package gs.boldthin.loyalty.screens

/** A font's kern pairs against the space glyph, in em: [after] = char then space, [before] = space then char. */
internal class SpaceKern(val after: Map<Char, Float>, val before: Map<Char, Float>)

internal object SpaceKerning {
    /** Font resource name -> CSS weight -> its space kerning. */
    val TABLE: Map<String, Map<Int, SpaceKern>> = mapOf(
${body}
    )
}
`)
console.log(`space-kerning: ${rows.length} font weights -> ${args.out}`)
for (const r of rows) console.log(`  ${r.res} ${r.weight}: after ${JSON.stringify(r.after)} before ${JSON.stringify(r.before)}`)
